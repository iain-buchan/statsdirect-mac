        /// <summary>
        /// expected normal order statistics
        /// </summary>
        /// <param name="i"></param>
        /// <param name="n"></param>
        /// <returns></returns>
        public static double expnos(int i, int n)
        {

            int ii = i;
            if (n < 1)
            {
                return 0.0;
            }
            if (i < 1) ii = 1;
            if (i > n) ii = n;
            int ioe = n % 2;
            int m = (n + 1) / 2;
            if (ii - m == 0 && ioe != 0)
            {
                return 0.0;
            }
            const double seta = Constant.DBL_MIN;
            double smexe = Math.Log(seta);
            double alogp5 = Math.Log(0.5);
            double f = 0.0;
            double fn = n + 1;
            double fr = n + 1 - ii;
            double fi = ii;
            fn = PDF.alogam(fn);
            fr = PDF.alogam(fr);
            fi = PDF.alogam(fi);
            double fff = fn - fr - fi;
            double ri = ii - 1;
            double rn = n - ii;
            double p = fff + q[152] + ri * r[1] + rn * r[304] + s[1];
            if (p >= smexe + alogp5) f = -0.5 * Math.Exp(p);
            for (int j = 2; j <= 152; j++)
            {
                p = fff + q[153 - j] + ri * r[j] + rn * r[305 - j] + s[j];
                if (p >= smexe) f -= Math.Exp(p);
            }
            for (int j = 153; j <= 303; j++)
            {
                p = fff + q[j - 152] + ri * r[j] + rn * r[305 - j] + s[j];
                if (p >= smexe) f += Math.Exp(p);
            }
            p = fff + q[152] + ri * r[304] + rn * r[1] + s[304];
            if (p >= smexe + alogp5) f += 0.5 * Math.Exp(p);
            return -.05 * f;
        }
