m <- length(p); n <- length(a); cuts <- sort(c(p,a))
sens <- vapply(cuts,function(x)sum(p>=x)/m,0.0)
spec <- vapply(cuts,function(x)sum(a<x)/n,0.0)
theta <- unname(stats::wilcox.test(p,a,exact=FALSE)$statistic)/(m*n)
v <- vapply(p,function(x)sum((x>a)+.5*(x==a))/n,0.0)
u <- vapply(a,function(x)sum((p>x)+.5*(p==x))/m,0.0)
se <- sqrt(stats::var(v)/m+stats::var(u)/n)
ci <- pmax(0,pmin(1,theta+c(-1,1)*stats::qnorm(.975)*se))
best <- which.max(sens+spec); cut <- cuts[best]
counts <- c(sum(p>=cut),sum(a>=cut),sum(p<cut),sum(a<cut))
interval <- function(k,N)c(k/N,stats::binom.test(k,N,conf.level=.95)$conf.int)
proportions <- rbind(interval(counts[1],m),interval(counts[4],n),interval(counts[1],sum(counts[1:2])),interval(counts[4],sum(counts[3:4])))
emit(1)
emit(c(length(cuts),cuts,sens,spec,theta,theta,se,ci,1,1,cut,cut,counts,as.vector(proportions)))
